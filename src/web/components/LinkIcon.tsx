/**
 * Renders a small brand mark for links to recognised services (GitHub, Jira,
 * Notion, etc.), falling back to a generic external-link glyph otherwise.
 */
export function LinkIcon({
	url,
	className,
}: {
	url: string;
	className?: string;
}) {
	const service = identifyLinkService(url);
	if (!service) {
		return <ExternalLink className={className} />;
	}
	if (service.id === "slack") {
		return <SlackIcon className={className} name={service.name} />;
	}
	return (
		<svg
			viewBox="0 0 24 24"
			fill="currentColor"
			role="img"
			aria-label={service.name}
			className={className}
		>
			<path d={SERVICE_ICON_PATHS[service.id]} />
		</svg>
	);
}

